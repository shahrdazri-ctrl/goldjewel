#!/usr/bin/env python3
"""Generate the app's operation catalog from the capability matrix.

The matrix is the single source of truth for which operations are in v1. This
script writes the Swift table the app shows, so the shell cannot drift from the
CSV by hand-editing.

  python Tools/operation_catalog.py           write App/Sources/OperationCatalog.swift
  python Tools/operation_catalog.py --check   fail if the Swift file is stale
"""
from __future__ import annotations

import argparse
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATRIX = os.path.join(ROOT, "08-reports", "capability-matrix.csv")
OUTPUT = os.path.join(ROOT, "07-ios-handoff", "App", "Sources", "OperationCatalog.swift")

# Operations whose behaviour the current app actually performs. Everything else
# in v1 has a visible entry point but is marked pending its builder family.
WIRED = {
    "ExecuteBuilderCommand",
    "DeleteBuilder",
    "GetActiveBuilderId",
    "GetAllBuilderGuids",
    "ReadJsonFromDocument",
    "WriteJsonToDocument",
    "GetActiveDocPath",
    "GetCurrentFileIsModified",
    "SetCurrentFileAsNoModified",
    "GetRingSizeRegionAbrvs",
    "GetRingSizesFromRegionAbrv",
    "GetDefaultRingSizeRegionAbrv",
    "SetDefaultRingSizeRegionAbrv",
    "ResizeRing",
}


def escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def generate() -> str:
    with open(MATRIX, encoding="utf-8", newline="") as fh:
        rows = [
            row
            for row in csv.DictReader(fh)
            if row["disposition"] == "v1"
        ]
    rows.sort(key=lambda row: (row["cluster"], row["operation"]))
    missing = WIRED - {row["operation"] for row in rows}
    if missing:
        raise ValueError(f"wired operations are not in v1: {sorted(missing)}")
    lines = [
        "// Generated by Tools/operation_catalog.py from 08-reports/capability-matrix.csv.",
        "// Do not edit by hand; change the matrix and regenerate.",
        "import Foundation",
        "",
        "struct AppOperation: Identifiable, Hashable {",
        "    let id: String",
        "    let cluster: String",
        "    let reason: String",
        "",
        "    var isWired: Bool { OperationCatalog.wired.contains(id) }",
        "}",
        "",
        "enum OperationCatalog {",
        "    static let wired: Set<String> = [",
    ]
    for name in sorted(WIRED):
        lines.append(f'        "{escape(name)}",')
    lines += ["    ]", "", "    static let all: [AppOperation] = ["]
    for row in rows:
        lines.append(
            "        AppOperation("
            f'id: "{escape(row["operation"])}", '
            f'cluster: "{escape(row["cluster"])}", '
            f'reason: "{escape(row["reason"])}")'
            + ","
        )
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not os.path.exists(MATRIX):
        print("missing capability matrix", file=sys.stderr)
        return 2
    text = generate()
    if args.check:
        if not os.path.exists(OUTPUT):
            print("missing generated operation catalog", file=sys.stderr)
            return 1
        if open(OUTPUT, encoding="utf-8").read() != text:
            print("OperationCatalog.swift is stale; run Tools/operation_catalog.py", file=sys.stderr)
            return 1
        print("operation catalog matches the capability matrix")
        return 0
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
