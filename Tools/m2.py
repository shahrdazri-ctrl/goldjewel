#!/usr/bin/env python3
"""M2: one command for the oracle corpus, the triage ledger and the matrix.

  python Tools/m2.py            capture corpus + regenerate both ledgers + report
  python Tools/m2.py --check    verify everything already committed (CI)

The report it writes, 08-reports/m2-report.md, records measured counts only; it
is regenerated from the artefacts, never hand-edited.
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPORTS = os.path.join(ROOT, "08-reports")
TRIAGE = os.path.join(REPORTS, "triage-ledger.csv")
MATRIX = os.path.join(REPORTS, "capability-matrix.csv")
CORPUS = os.path.join(ROOT, "05-evidence", "corpus", "v1", "manifest.json")
REPORT = os.path.join(REPORTS, "m2-report.md")

TRIAGE_TOTAL = 50_134
MATRIX_TOTAL = 254
DISPOSITIONS = {"v1", "defer", "drop", "out-of-scope"}
CLASSES = {"port-as-is", "port-with-new-geometry", "drop"}


def read_csv(path: str) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def run(args: list[str]) -> int:
    print("$ " + " ".join(args[1:]), flush=True)
    return subprocess.run(args, cwd=ROOT).returncode


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    failures: list[str] = []
    py = sys.executable

    if not args.check:
        if run([py, "Tools/triage.py"]) != 0:
            failures.append("triage.py failed")
        if run([py, "Tools/capability_matrix.py"]) != 0:
            failures.append("capability_matrix.py failed")
        if run([py, "Tools/build_corpus.py"]) != 0:
            failures.append("build_corpus.py failed")
    else:
        if run([py, "Tools/build_corpus.py", "--check"]) != 0:
            failures.append("corpus check failed")

    for path, label in ((TRIAGE, "triage ledger"), (MATRIX, "capability matrix"), (CORPUS, "corpus manifest")):
        if not os.path.exists(path):
            failures.append(f"missing {label}: {os.path.relpath(path, ROOT)}")

    triage_rows = read_csv(TRIAGE) if os.path.exists(TRIAGE) else []
    matrix_rows = read_csv(MATRIX) if os.path.exists(MATRIX) else []
    manifest = json.load(open(CORPUS, encoding="utf-8")) if os.path.exists(CORPUS) else {}

    if len(triage_rows) != TRIAGE_TOTAL:
        failures.append(f"triage rows {len(triage_rows)} != {TRIAGE_TOTAL}")
    bad_class = {r["class"] for r in triage_rows} - CLASSES
    if bad_class:
        failures.append(f"triage classes {sorted(bad_class)}")
    bad_disposition = {r["disposition"] for r in matrix_rows} - DISPOSITIONS
    if bad_disposition:
        failures.append(f"matrix dispositions {sorted(bad_disposition)}")
    if len(matrix_rows) != MATRIX_TOTAL:
        failures.append(f"matrix rows {len(matrix_rows)} != {MATRIX_TOTAL}")
    if manifest and manifest.get("d_only", {}).get("violations"):
        failures.append("D: audit recorded violations")

    triage_by_class = collections.Counter(r["class"] for r in triage_rows)
    triage_by_rule = collections.Counter(r["rule"] for r in triage_rows)
    matrix_by_disposition = collections.Counter(r["disposition"] for r in matrix_rows)
    corpus = manifest.get("corpora", {})
    guard = manifest.get("d_only", {}).get("guard", {})

    lines = [
        "# M2 — oracle corpus, triage ledger, capability matrix",
        "",
        f"Generated by `python Tools/m2.py` at {datetime.now(timezone.utc).isoformat()}.",
        "Every number below is read from the committed artefact beside it.",
        "",
        "## Ground truth status",
        "",
        "The vendor assemblies were **not executed**. `CSBlocks.mgp` is a mixed-mode Rhino plugin, so",
        "loading it outside Rhino fails in `Rhino_DotNet.dll` initialisation (`0x8007045A`,",
        "`ERROR_DLL_INIT_FAILED`). Corpus v1 therefore records IL and metadata, not observed geometry:",
        "every string, numeric constant, call edge, field access and parameter default for the captured",
        "types, with IL offsets. Behavioural capture remains the one open verification gap and requires a",
        "Rhino-hosted run; it is tracked in `08-reports/limitations.md`.",
        "",
        "## Corpus v1",
        "",
        f"Assembly: `{manifest.get('assembly', {}).get('file', 'missing')}` ",
        f"SHA-256 `{manifest.get('assembly', {}).get('sha256', 'missing')}`.",
        "",
        "| Corpus | Types | Methods | Instructions | Strings | Numeric constants | Call edges | Bytes |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, record in corpus.items():
        s = record["summary"]
        lines.append(
            f"| `{name}` | {s['types']} | {s['methods']} | {s['instructions']} | {s['strings']} | "
            f"{s['numeric_constants']} | {s['call_edges']} | {record['bytes']:,} |"
        )

    lines += [
        "",
        "## Method triage",
        "",
        f"Total methods classified: **{len(triage_rows):,}**.",
        "",
        "| Class | Methods | Share |",
        "|---|---:|---:|",
    ]
    for cls in ("port-as-is", "port-with-new-geometry", "drop"):
        count = triage_by_class.get(cls, 0)
        share = 100.0 * count / len(triage_rows) if triage_rows else 0.0
        lines.append(f"| `{cls}` | {count:,} | {share:.1f} % |")
    lines += [
        "",
        f"Unmatched default rule: **{triage_by_rule.get('default', 0):,}** methods. These stay visible so",
        "each can be reviewed rather than silently absorbed into an assembly-wide rule.",
        "",
        "## Capability matrix (254 operations)",
        "",
        "| Disposition | Operations |",
        "|---|---:|",
    ]
    for disposition in ("v1", "defer", "drop", "out-of-scope"):
        lines.append(f"| `{disposition}` | {matrix_by_disposition.get(disposition, 0)} |")

    lines += [
        "",
        "## D:-only rule",
        "",
        f"Harness guard: writing to a non-`D:` output was refused with exit code **{guard.get('exit_code')}**",
        f"({'refused' if guard.get('refused') else 'NOT refused'}). Recorded C: root deltas: "
        f"**{len(manifest.get('d_only', {}).get('violations', []))} violations**.",
        "",
        "The harness checks the output root before creating any file, and the capture redirects",
        "`NUGET_PACKAGES`, `DOTNET_CLI_HOME`, `TMP` and `TEMP` under `D:\\REA-LAB\\02-toolchain`.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "python Tools/m2.py            # licensed Windows machine with the D: mirror",
        "python Tools/m2.py --check    # any machine, validates committed artefacts",
        "```",
    ]

    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

    print()
    print(f"triage {len(triage_rows)} methods: " + ", ".join(f"{k} {v}" for k, v in triage_by_class.items()))
    print(f"matrix {len(matrix_rows)} ops: " + ", ".join(f"{k} {v}" for k, v in matrix_by_disposition.items()))
    for name, record in corpus.items():
        s = record["summary"]
        print(f"corpus {name}: {s['types']} types, {s['methods']} methods, {s['strings']} strings")
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")

    if failures:
        print()
        for failure in failures:
            print(f"FAIL {failure}", file=sys.stderr)
        return 1
    print("M2 checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
